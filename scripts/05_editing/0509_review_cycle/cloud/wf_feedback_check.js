// Облачный сверщик «Обратной связи по кату vN» (Claude Code Workflow tool). ОДИН агент, только текст, второго нет.
// Вопрос агенту один: закрыл ли монтажёр пункт ПРОШЛОГО ТЗ в НОВОМ кате. Контракт: docs/feedback_v1.md §6.
// Запуск — из вызова, который печатает shared/feedback_call.py --print-call:
//   Workflow({scriptPath: '.../cloud/wf_feedback_check.js', args: {code, cut_version, prev_cut_version, film,
//            film_path, items_path, out_path, packet_sha, n_items, duration_sec, film_chars, est_tokens}})
// Ни лента, ни пункты в промпт НЕ кладутся: агент получает ПУТИ и читает сам (лента ≈ 25 К токенов, пункты ≈ 20 К).
// Чувствительных пунктов и кадров в пакете нет — их туда не кладёт feedback_call.py (assert в коде и в самотесте).
// Результат агент пишет Write'ом в out_path ДО возврата (схема feedback-check-v1); возвращает только короткую сводку.
// Приём — shared/feedback_call.py --apply: каждая цитата ищется в ленте дословно, выдуманная → вердикт выброшен.
export const meta = {
  name: 'review-feedback-check',
  description: 'One text-only agent checks whether the editor closed each item of the previous edit list in the new cut; verdicts with verbatim quotes',
  phases: [
    { title: 'Check', detail: 'один агент: лента нового ката + пункты прошлого ТЗ → вердикт по каждому пункту с дословной цитатой' },
  ],
}

const A = args || {}
const CODE = A.code || 'кат'
const CUT = A.cut_version || ''
const PREV = A.prev_cut_version || 'прошлой версии'
const FILM = A.film || 'документальный фильм канала'
const FILM_PATH = A.film_path || ''
const ITEMS_PATH = A.items_path || ''
const OUT = A.out_path || ''
const SHA = A.packet_sha || ''
const N = A.n_items || 0
const DUR = A.duration_sec ? Math.floor(A.duration_sec / 60) + ':' + String(Math.floor(A.duration_sec % 60)).padStart(2, '0') : ''

const SUMMARY_SCHEMA = {
  type: 'object',
  properties: {
    written: { type: 'boolean', description: 'файл результата записан Write\'ом ДО возврата' },
    out_path: { type: 'string', description: 'куда записан файл результата' },
    packet_sha: { type: 'string', description: 'скопировано из пакета пунктов без изменений' },
    cut_version: { type: 'string', description: 'скопировано из пакета пунктов без изменений' },
    n_items: { type: 'integer', description: 'сколько пунктов было в пакете' },
    n_verdicts: { type: 'integer', description: 'сколько вердиктов записано в файл (должно равняться n_items)' },
    closed: { type: 'integer' },
    open: { type: 'integer' },
    unknown: { type: 'integer' },
    overturned: { type: 'array', items: { type: 'integer' }, description: 'номера n, где вывод кода «закрыто» не подтвердился' },
    notes: { type: 'string', description: 'одна-две фразы: что помешало (если помешало)' },
  },
  required: ['written', 'packet_sha', 'cut_version', 'n_verdicts', 'closed', 'open', 'unknown'],
}

const prompt =
  `Ты — сверщик монтажа документального фильма: ${FILM} (${CODE}${CUT ? ', новый кат ' + CUT : ''}${DUR ? ', длительность ' + DUR : ''}).\n` +
  `Монтажёр получил список правок по кату ${PREV} и сдал новый кат. Твой единственный вопрос по КАЖДОМУ пункту:\n` +
  `закрыл ли монтажёр этот пункт в новом кате. Ты работаешь только с текстом — видео и кадров у тебя нет.\n\n` +
  `ВХОДЫ (прочитай оба файла Read'ом целиком; лента длинная — читай частями через offset/limit, ничего не пропуская):\n` +
  `1. Лента нового ката: ${FILM_PATH || '(путь не передан — возьми поле film из пакета пунктов)'}\n` +
  `   Строки идут по времени. Три вида строк:\n` +
  `     «M:SS [С1] текст»          — речь (кто говорит — в шапке ленты);\n` +
  `     «ЭКРАН M:SS–M:SS «текст»»  — надпись, которая стоит на экране в этот промежуток (распознана машиной, возможны огрехи букв);\n` +
  `     «VLM M:SS описание»        — машинное описание кадра (по-английски) и, после «текст в кадре:», то, что она прочла.\n` +
  `2. Пакет пунктов (JSON): ${ITEMS_PATH || '(путь не передан)'}\n` +
  `   В каждом пункте: n — номер; title, category; now — что было не так; do — что просили сделать; where — где;\n` +
  `   look — где искать в НОВОМ кате (таймкоды внутри now/do/where уже пересчитаны на новый кат, но приблизительно);\n` +
  `   targets — надписи или реплики, которые должны появиться (если есть); code_status и code_evidence — предварительный вывод кода.\n\n` +
  `ПРАВИЛА ВЕРДИКТА (по каждому пункту ровно один вердикт, всего их должно быть ${N || 'столько же, сколько пунктов в пакете'}):\n` +
  `• status = closed — монтажёр сделал то, о чём просили, и это ВИДНО в ленте. open — просьба не выполнена, и это ВИДНО в ленте\n` +
  `  (фраза, которую просили убрать, на месте; надписи, которую просили поставить, в нужном месте нет, а соседние реплики есть).\n` +
  `  unknown — по ленте судить нельзя. При любом сомнении — unknown: ложное «закрыто» хуже честного «не знаю».\n` +
  `• quote — ДОСЛОВНАЯ выдержка из ленты, не длиннее 120 знаков, скопированная из одной строки (или из соседних строк речи подряд)\n` +
  `  без правки падежей, без сокращений, без многоточий и без таймкода. Код после тебя найдёт цитату в ленте в пределах 20 секунд\n` +
  `  от твоего tc; не найдёт — вердикт будет выброшен. Ничего не цитируй по памяти и не пересказывай.\n` +
  `• tc — M:SS строки ленты, из которой взята цитата. source — speech (речь), screen (строка ЭКРАН) или vlm (строка VLM).\n` +
  `• Вырез (category = cut): доказательство выреза — ОТСУТСТВИЕ фразы, одной цитатой его не показать. Для closed дай ДВЕ цитаты\n` +
  `  вокруг стыка: quote + tc — последние слова, которые звучат ПЕРЕД местом выреза; quote2 + tc2 — первые слова, которые звучат\n` +
  `  сразу ПОСЛЕ него. Цитаты должны стоять в ленте вплотную (между ними — не более 4 слов) и не содержать вырезанной фразы.\n` +
  `  Перед этим поищи вырезанную фразу по всей ленте (её могли переставить, а не убрать). Если фраза звучит — это open, и quote — она сама.\n` +
  `• Надписи (graphics) и главы (structure): closed — только если нужный текст есть в строке ЭКРАН или «текст в кадре» у VLM;\n` +
  `  цитируй эту строку. Огрехи распознавания в одну-две буквы — не повод для open; другое слово, другая фамилия, другая цифра — повод.\n` +
  `  Если в targets несколько надписей — closed только когда нашлись ВСЕ; нашлась часть — open, в note перечисли, чего нет.\n` +
  `  Если у пункта есть поле targets_held — часть целей тебе не показана: closed по такому пункту не ставь (open при явной нехватке, иначе unknown).\n` +
  `• Кодовому «закрыто» (code_status = closed) верить нельзя: код искал похожие слова и мог найти их в другом месте фильма.\n` +
  `  Перепроверь каждое сам. Не подтвердилось — ставь open (с цитатой) или unknown (без неё); этого достаточно, чтобы снять «закрыто».\n` +
  `• Кодовому «осталось» (code_status = open) тоже не верь на слово: монтажёр мог исправить иначе, чем просили.\n` +
  `• Место цитаты у closed: только из окна look этого пункта или рядом (до минуты) с таймкодом, который назван в его now/do/where.\n` +
  `  Цитата из другого места фильма ничего не закрывает — приёмка такой closed выбросит. Если look — «время неизвестно», годится любое место.\n` +
  `  confidence — числом (не строкой), tc — строго «M:SS» одной строки ленты.\n` +
  `• Не придумывай того, чего в ленте нет. Цвет, звук, громкость, музыка, склейки, крупность плана, перебивки и вставки видео\n` +
  `  без строки VLM, которая их описывает, — unknown. Отсутствие строки VLM ничего не доказывает: описаны не все кадры.\n` +
  `• look = «время в новом кате неизвестно…» — ищи по всей ленте; не нашёл — unknown.\n` +
  `• confidence — от 0 до 1, честно. closed с confidence ниже 0.8 принят не будет — в таком случае сразу ставь unknown.\n` +
  `• note — ОДНА человеческая фраза для монтажёра: что именно видно в новом кате. Без таймкодов внутри, без слов «лента», «пакет»,\n` +
  `  «код», «VLM», «OCR», без английских слов и без номеров пунктов. Пример: «подпись куратора стоит, фамилия написана верно»,\n` +
  `  «фраза про кредит по-прежнему звучит», «по тексту не проверить: это правка цвета».\n\n` +
  `ВЫХОД. Запиши Write'ом в файл ${OUT || '(поле out из пакета пунктов)'} ДО возврата JSON ровно такого вида:\n` +
  `{"schema": "feedback-check-v1", "cut_version": "<скопируй из пакета>", "packet_sha": "<скопируй из пакета${SHA ? ', там ' + SHA : ''}>",\n` +
  ` "verdicts": [{"n": 40, "status": "closed|open|unknown", "tc": "11:16", "quote": "…", "source": "speech|screen|vlm",\n` +
  `               "confidence": 0.9, "note": "…", "tc2": "11:19", "quote2": "…"}]}\n` +
  `tc2 и quote2 — только у closed для category = cut. У unknown поля tc и quote можно оставить пустыми строками.\n` +
  `Вердикты — в порядке пунктов пакета, каждый n ровно один раз, ни один пункт не пропущен. packet_sha и cut_version копируй\n` +
  `из пакета буква в букву: по ним приёмка отличает ответ по этому кату от устаревшего.\n` +
  `После записи файла верни короткую сводку по схеме StructuredOutput (сколько closed / open / unknown, какие кодовые «закрыто» не\n` +
  `подтвердились). Сами вердикты в ответе не повторяй — они уже в файле.`

phase('Check')
const summary = await agent(prompt, { label: `feedback-check:${CODE}${CUT ? ':' + CUT : ''}`, phase: 'Check', schema: SUMMARY_SCHEMA, effort: 'high' })

if (!summary) {
  log('агент-сверщик не вернул результат (пропущен или упал) — см. journal.jsonl; повторный запуск возьмёт кэш')
  return { summary: null, out_path: OUT, packet_sha: SHA }
}
if (SHA && summary.packet_sha !== SHA) log(`⚠️ агент вернул packet_sha ${summary.packet_sha}, ждали ${SHA} — приёмка такой файл отклонит`)
if (N && summary.n_verdicts !== N) log(`⚠️ вердиктов ${summary.n_verdicts}, пунктов в пакете ${N} — пропущенные останутся как были`)
log(`сверка ${CODE} ${CUT}: закрыто ${summary.closed} · осталось ${summary.open} · не проверить ${summary.unknown}` +
  (Array.isArray(summary.overturned) && summary.overturned.length ? ` · кодовое «закрыто» снято у ${summary.overturned.join(', ')}` : '') +
  ` → ${OUT}`)

return { summary, out_path: OUT, packet_sha: SHA }
