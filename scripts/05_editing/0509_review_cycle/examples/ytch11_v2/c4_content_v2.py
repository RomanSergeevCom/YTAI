def spec_gap(rows, item, frames_wanted):
    _, src_label, transcript, status, screen, show, frspec = item
    img = None
    if frspec:
        if frspec[0] == 'cut':
            img = frspec[1]
        elif frspec[0] == 'scene':
            _, scene, ssec, fname = frspec
            img = ins_frame_scene(scene, ssec, fname)
        if img:
            frames_wanted.add(img)
    rows.append({'kind': 'row', 'img': img,
                 'cells': ['', src_label, status, transcript, screen, show],
                 'shade': 'green'})


for item in ROWS_SPEC:
    kind = item[0]
    if kind in ('act', 'ch'):
        rows.append({'kind': 'act' if kind == 'act' else 'chapter', 'text': item[1]})
        continue
    if kind == 'cut':
        _, a, b, status, screen, show, shade, fov = item
        a, b = B(a), B(b)
        assert b > a, (a, b, status)
        fr = fov or pick_frame(a, b)
        frames_wanted.add(fr)
        cut_bounds.append((a, b))
        rows.append({'kind': 'row', 'img': fr,
                     'cells': ['', 'v2 %s–%s\n%s' % (tc(a), tc(b), src_of(a, b)),
                               status, cut_text(a, b), screen, show],
                     'shade': shade})
        for after in sorted(gaps_by_after):
            if a < after <= b:
                for g in gaps_by_after.pop(after, []):
                    spec_gap(rows, g, frames_wanted)
        continue
    if kind == 'gap':
        spec_gap(rows, item, frames_wanted)


