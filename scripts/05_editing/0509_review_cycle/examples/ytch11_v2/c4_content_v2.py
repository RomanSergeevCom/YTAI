def find_t(phrase, occ=1):
    ph = [re.sub(r'[^а-яa-z0-9]', '', x.lower().replace('ё', 'е')) for x in phrase.split()]
    ph = [x for x in ph if x]
    n, k = len(ph), 0
    for i in range(len(NW) - n):
        if NW[i:i+n] == ph:
            k += 1
            if k == occ:
                return W[i][0]
    # диагностика: показать окна с первым словом
    hits = [i for i, x in enumerate(NW) if x == ph[0]]
    for i in hits[:6]:
        print('  near:', ' '.join(x[2] for x in W[max(0, i-2):i+8]))
    raise SystemExit(f'!! anchor not found: {phrase!r}')


def cut_text(a, b):
    return ' '.join(w for s, e, w in W if a <= s < b).strip()


def tc(t):
    return '%d:%02d' % (int(t) // 60, int(t) % 60)


MAPS = json.load(open(os.path.join(WORK, 'map_src.json'), encoding='utf-8'))


def src_of(a, b):
    hits = [m for m in MAPS if m['v2_t0'] < b and m['v2_t1'] > a
            and min(b, m['v2_t1']) - max(a, m['v2_t0']) > 0.25*(b-a)]
    if not hits:
        return ''
    m = max(hits, key=lambda m: min(b, m['v2_t1'])-max(a, m['v2_t0']))
    off0 = m['src_t0'] + max(0, a - m['v2_t0'])
    return '%s %s' % (m['scene'].split('_')[0], tc(off0))


# ------------------------------------------------- clip offsets (ingest)
_ing = json.load(open(ING, encoding='utf-8'))['sync']


def _iso(t):
    return datetime.datetime.fromisoformat(t.replace('Z', '+00:00'))


def _clip_start_in_scene(scene, clip_path):
    """секунда сцены, на которой начинается клип"""
    s = _ing[scene]
    delta = s['cameras']['CAM1-FX3']['delta_sec']
    t0 = _iso(s['scene_t0'])
    p = subprocess.run(['ffprobe', '-v', 'error', '-show_entries',
                        'format_tags=creation_time', '-of',
                        'default=noprint_wrappers=1:nokey=1', clip_path],
                       capture_output=True, text=True)
    ct = _iso(p.stdout.strip())
    return (ct - t0).total_seconds() + delta


_clip_cache = {}


def ins_frame_scene(scene, scene_sec, name):
    """кадр по scene-tc: найти клип сцены, попадающий в это время"""
    out = os.path.join(INS_DIR, name)
    if os.path.exists(out):
        return name
    sdir = os.path.join(P, '01_Source', scene)
    clips = sorted(f for f in os.listdir(sdir) if f.endswith('.MP4'))
    best = None
    for c in clips:
        cp = os.path.join(sdir, c)
        key = (scene, c)
        if key not in _clip_cache:
            try:
                _clip_cache[key] = _clip_start_in_scene(scene, cp)
            except Exception:
                _clip_cache[key] = None
        st = _clip_cache[key]
        if st is not None and st <= scene_sec:
            if best is None or st > best[1]:
                best = (cp, st)
    if not best:
        print('!! no clip for', scene, scene_sec)
        return None
    local = scene_sec - best[1]
    subprocess.run(['ffmpeg', '-hide_banner', '-v', 'error', '-ss', str(max(0, local)),
                    '-i', best[0], '-frames:v', '1', '-vf', 'scale=1280:-2',
                    '-q:v', '3', out], check=False)
    print('  ins %s <- %s @%.0fs(local %.0f)' % (name, os.path.basename(best[0]),
                                                 scene_sec, local))
    return name if os.path.exists(out) else None


def B(x):
    if isinstance(x, (int, float)):
        return float(x)
    return find_t(x[1], x[2] if len(x) > 2 else 1)


