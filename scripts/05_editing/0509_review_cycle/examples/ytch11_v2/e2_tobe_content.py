def _iso(t):
    return datetime.datetime.fromisoformat(t.replace('Z', '+00:00'))


_cc = {}


def _clip_start(scene, cp):
    key = (scene, os.path.basename(cp))
    if key not in _cc:
        s = _ing[scene]
        delta = s['cameras']['CAM1-FX3']['delta_sec']
        pr = subprocess.run(['ffprobe', '-v', 'error', '-show_entries',
                             'format_tags=creation_time', '-of',
                             'default=noprint_wrappers=1:nokey=1', cp],
                            capture_output=True, text=True)
        _cc[key] = (_iso(pr.stdout.strip()) - _iso(s['scene_t0'])).total_seconds() + delta
    return _cc[key]


def frame_scene(scene, ssec, name):
    out = os.path.join(INS_DIR, name)
    if os.path.exists(out):
        return name
    sdir = os.path.join(P, '01_Source', scene)
    best = None
    for c in sorted(f for f in os.listdir(sdir) if f.endswith('.MP4')):
        cp = os.path.join(sdir, c)
        try:
            st = _clip_start(scene, cp)
        except Exception:
            continue
        if st <= ssec and (best is None or st > best[1]):
            best = (cp, st)
    if not best:
        return None
    subprocess.run(['ffmpeg', '-hide_banner', '-v', 'error', '-ss',
                    str(max(0, ssec - best[1])), '-i', best[0], '-frames:v', '1',
                    '-vf', 'scale=1280:-2', '-q:v', '3', out], check=False)
    return name if os.path.exists(out) else None


def frame_clip(path, sec, name):
    out = os.path.join(INS_DIR, name)
    if not os.path.exists(out):
        subprocess.run(['ffmpeg', '-hide_banner', '-v', 'error', '-ss', str(sec),
                        '-i', path, '-frames:v', '1', '-vf', 'scale=1280:-2',
                        '-q:v', '3', out], check=False)
    return name if os.path.exists(out) else None


def f_v2(mmss):
    m, s = mmss.split(':')
    return 'f%04d.jpg' % (int(m) * 60 + int(s) + 1)


