def src_text(scene, filt, t0, t1):
    out = []
    for seg in _a['segments']:
        if seg['scene'] != scene:
            continue
        if filt and filt not in seg['source_file']:
            continue
        for w in seg.get('words') or []:
            s = float(w['s'])
            if t0 <= s <= t1:
                out.append((s, w['w']))
    out.sort()
    t = ' '.join(w for s, w in out)
    if len(t) < 20:
        print('!! src_text short:', scene, filt, t0, t1, '->', len(t))
    return t


def span_text(spec):
    if spec is None:
        return '—'
    kind = spec[0]
    if kind == 'v2':
        return cut_text(spec[1], spec[2])
    if kind == 'src':
        return src_text(spec[1], spec[2], spec[3], spec[4])
    if kind == 'multi':
        return '\n···\n'.join(span_text(x) for x in spec[1])
    if kind == 'text':
        return spec[1]
    raise ValueError(spec)


def para(text, target=300):
    """разбить длинный транскрипт на абзацы по границам предложений (~target зн.)"""
    parts = []
    for chunk in text.split('\n'):
        if not chunk.strip():
            continue
        sents = re.split(r'(?<=[.?!…]) +', chunk)
        cur = ''
        for s in sents:
            if cur and len(cur) + len(s) > target:
                parts.append(cur.strip())
                cur = s
            else:
                cur = (cur + ' ' + s).strip()
            # слишком длинное «предложение» без пунктуации — резать по словам
            while len(cur) > 2 * target:
                ws = cur.split(' ')
                head, rest = [], []
                ln = 0
                for w in ws:
                    if ln < target:
                        head.append(w); ln += len(w) + 1
                    else:
                        rest.append(w)
                parts.append(' '.join(head))
                cur = ' '.join(rest)
        if cur.strip():
            parts.append(cur.strip())
    return '\n\n'.join(parts)  # пустая строка между абзацами — легче читать (Роман)


